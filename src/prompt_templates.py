import json
from llm_client import ask_gigachat

def analyze_review_prompt(review_text: str) -> str:
    prompt = f"""
Ты — старший аналитик отзывов. Твоя задача — извлечь структурированные данные из отзыва и вернуть ТОЛЬКО валидный JSON без markdown-обёртки (без ```json ... ```), без пояснений и лишнего текста.

Отзыв для анализа:
\"\"\"{review_text}\"\"\"

Инструкция:
1. Определи общую тональность (sentiment): "позитивная", "нейтральная" или "негативная".
2. Выпиши конкретные плюсы, упомянутые автором (pros). Если их нет — пустой список [].
3. Выпиши конкретные минусы/претензии автора (cons). Если их нет — пустой список [].
4. Оцени полезность отзыва для других покупателей по шкале от 0 до 10 (helpfulness_score).
5. Определи категорию товара (category) по содержимому отзыва (например, "электроника", "одежда", "бытовая техника").

Формат ответа — строго следующий JSON:
{{
  "sentiment": "...",
  "pros": ["...", "..."],
  "cons": ["...", "..."],
  "helpfulness_score": <число от 0 до 10>,
  "category": "..."
}}

Пример правильного ответа на отзыв "Зарядка греется, но кабель мягкий и удобный":
{{
  "sentiment": "нейтральная",
  "pros": ["мягкий и удобный кабель"],
  "cons": ["греется во время работы"],
  "helpfulness_score": 6,
  "category": "электроника"
}}

Верни только JSON.
    """
    return prompt

if __name__ == "__main__":
    # Сырой отзыв для анализа
    user_review = """ Купил эти наушники вчера. Звук чистый, объемный, за свои деньги топ. Однако амбюшуры слишком жесткие, уши начинают болеть через час использования"""
    
    print("1. Формируем сложный промпт...")
    final_prompt = analyze_review_prompt(user_review)
    
    print("2. Отправляем запрос в GigaChat...")
    raw_response = ask_gigachat(final_prompt, temperature=0.1)
    
    print(f"\nСырой ответ от модели:\n{raw_response}\n")
    
    print("3. Проверяем валидность полученного JSON...")
    try:
        parsed_json = json.loads(raw_response.strip())
        print("Успех! Данные успешно преобразованы в Python dict: ")
        print(f"Тональность: {parsed_json.get('sentiment')}")
        print(f"Плюсы: {parsed_json.get('pros')}")
        print(f"Минсы: {parsed_json.get('cons')}")
    except json.JSONDecodeError:
        print("Ошибка: Модель нарушила формат и вернула невалидный JSON.")
        
    